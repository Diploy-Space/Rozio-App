    String? tags,
  }) async {
    return await auctionRepoInterface.relaunchAuctionProductV6(
      auctionId: auctionId,
      addAuctionProduct: addAuctionProduct,
      categoryId: categoryId,
      brandId: brandId,
      productType: productType,
      itemCondition: itemCondition,
      startingPrice: startingPrice,
      minimumIncrementAmount: minimumIncrementAmount,
      maximumDecrementAmount: maximumDecrementAmount,
      startTime: startTime,
      endTime: endTime,
      shippingFee: shippingFee,
      returnPolicy: returnPolicy,
      thumbnail: thumbnail,
      images: images,
      retainedImages: retainedImages,
      videoType: videoType,
      youtubeVideo: youtubeVideo,
      customerVideo: customerVideo,
      taxIds: taxIds,
      metaTitle: metaTitle,
      metaDescription: metaDescription,
      metaImageFile: metaImageFile,
      currentCurrencyCode: currentCurrencyCode,
      tags: tags,
    );
